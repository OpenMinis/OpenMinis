/**
 * T-streaming-side-channel: overlay any active [StreamingDelta]s on top of
 * the canonical [messages] list, producing the snapshot
 * [buildFlatChatItems] should fold over. The original [messages] list is
 * never mutated; affected entries are replaced via `copy()` so downstream
 * keying / equality stays correct. When [streaming] is empty the input is
 * returned as-is to skip the per-element walk on idle frames.
 */
internal fun mergeStreamingOverlay(
    messages: List<ChatMessage>,
    streaming: Map<String, StreamingDelta>,
): List<ChatMessage> {
    if (streaming.isEmpty()) return messages
    return messages.map { m ->
        val delta = streaming[m.id] ?: return@map m
        // [T-android-stream-duplicate-text] `delta.content` is the WHOLE
        // assistant reply accumulated across every tool round, while
        // `delta.toolBlocks` is that same reply split chronologically into
        // per-round text/tool blocks (the producer appends each round's text
        // block and keeps advancing only that block; rounds never repeat
        // earlier text). Overwriting one block with the cumulative string
        // therefore duplicated everything before it: whichever text block was
        // last kept its own fragment AND re-rendered rounds 1..N-1 again, so a
        // turn with text A → tool → text B painted "A" then "A+B".
        //
        // The blocks are the authority for what each row renders, so take them
        // verbatim:
        //  - delta.toolBlocks non-empty → newest per-round snapshot. copy() it
        //    (the delta list is shared) but never rewrite a block's content.
        //  - delta.toolBlocks empty but the canonical message already carries
        //    blocks → keep those. Rewriting the last text block with the
        //    cumulative content would re-introduce the exact duplication.
        //  - canonical blocks also empty (pre-first-block turn) → stay empty;
        //    the typing indicator renders and the legacy fallback below is
        //    driven by content == "" while nothing has arrived.
        // Fall back to m.toolBlocks rather than [] so a machine-migration
        // streaming message without a toolBlocks list keeps its blocks.
        val blocks = when {
            delta.toolBlocks.isNotEmpty() -> delta.toolBlocks
            m.toolBlocks.isNotEmpty() -> m.toolBlocks
            else -> emptyList()
        }
        m.copy(
            // Content stays authoritative on its own field (non-render
            // consumers: persistence, copy/translate fallbacks).
            content = delta.content,
            isStreaming = true,
            toolBlocks = blocks,
            isAwaitingModelResponse = delta.isAwaitingModelResponse,
        )
    }
}

// ── [T-android-round-collapse] Round model ──────────────────────────────
//
// A round = one user message + every assistant/system message after it up to
// the next user message. The fold unit is the ROUND, not the assistant
// message: the user's mental model is "我问一句 → AI 干活 → 回复", so a
// resume continuation or a group-chat reply that lands inside the same round
// must not sprout its own fold bar — one round, one bar, round-wide totals.
//
// Fold rules (taixu RoundCollapse projection + OmniBot one-expression state):
//  1. foldable steps ≤ 2 → never fold (a bar summarising two rows is noise);
//  2. a RUNNING round is always fully open — effectiveExpanded =
//     isRunning || expanded — so completion auto-collapses with no trigger
//     of its own: the round simply stops forcing itself open;
//  3. a collapsed round keeps its LATEST 2 steps visible (the "刚才在干什
//     么" tail) and folds the rest into the summary bar;
//  4. the bar is owned by the round's LAST assistant message (messageId ==
//     that message's id, which is also the expansion key), emitted after its
//     blocks — visually below the round's reply under reverseLayout
//     (T-android-fold-bar-order).
private class ChatRound(
    val key: String,
    val lastAssistantIdx: Int,
    val isRunning: Boolean,
    val foldableSteps: Int,
    val thinkingCount: Int,
    val toolCount: Int,
    val hasFailure: Boolean,
    val totalMs: Long,
    val processTools: List<ProcessToolRef>,
    /**
     * [P-process-card] Contiguous process runs inside the round, split by
     * visible reply text. One card per run (the reference layout: a capsule
     * "已调用 N 个工具" between paragraphs), not one bar per round. The bar
     * is emitted after the run's last block, so under reverseLayout it sits
     * visually ABOVE the reply that follows it.
     */
    val segments: List<ProcessSegment>,
)

/**
 * One stretch of process blocks between reply texts. [lastBlockId] is the
 * block the card is emitted after; [firstBlockId] anchors the expanded
 * card's step rows so they render inside the card instead of in the list.
 */
private class ProcessSegment(
    val messageIdx: Int,
    val firstBlockId: String,
    val lastBlockId: String,
    val blockIds: Set<String>,
    val thinkingCount: Int,
    val toolCount: Int,
    val hasFailure: Boolean,
    val totalMs: Long,
    val steps: List<ProcessStepRef>,
    val running: Boolean,
    /**
     * [P-process-card] What the card is doing right now, for the live header:
     * "thinking" while reasoning streams, "tool" while a tool runs, "" once
     * the run has settled. "输出中" was dropped — reply text ends the card
     * immediately, so that state would flash for a single frame.
     */
    val activity: String,
    /** Title of the tool currently running, empty otherwise. */
    val activityTitle: String,
    /** Start of the run's earliest still-open step; the card ticks from it. */
    val startedAtMs: Long,
)

/**
 * One row of an expanded process card: a thinking block or a tool block,
 * in the order it happened. Pure data — the composable decides icons.
 */
internal data class ProcessStepRef(
    val id: String,
    val kind: String,
    val title: String,
    val status: ToolBlockStatus?,
    val durationMs: Long,
    val running: Boolean,
)

/** Rounds with fewer foldable steps than this never fold (rule 1). */
private const val ROUND_MIN_FOLDABLE_STEPS = 3

/** A process run shorter than this stays inline (a card for one row is noise). */
private const val SEGMENT_MIN_STEPS = 2

/**
 * [message]'s blocks after the speaker / sub-agent visibility filters.
 * Shared by the round pre-pass and the row loop so the summary bar's counts
 * can never drift from what the rows actually render.
 */
private fun effectiveBlocks(message: ChatMessage, activeSubAgentToolIds: Set<String>): List<AssistantBlock> {
    // Finished group utterances drop their tool cards. A live speaker still
    // shows the current thinking block or tool card.
    val hideSpeakerTools = !message.speakerName.isNullOrBlank() &&
        !message.isStreaming && !message.isAwaitingModelResponse
    if (!hideSpeakerTools && activeSubAgentToolIds.isEmpty()) return message.toolBlocks
    // A sub-agent transcript card is hidden only while its run is still
    // live in the top bar — the bar and the card would otherwise show the
    // same run twice. Once the run finishes the bar drops it, so the card
    // must come back here: with the old "hide whenever the bar is on" rule a
    // completed sub-agent left no trace anywhere on the session page.
    fun hiddenSubAgent(block: AssistantBlock): Boolean =
        isSubAgentTranscriptCard(block) &&
            (block.id in activeSubAgentToolIds ||
                block.id.substringBefore("#sub-") in activeSubAgentToolIds)
    return message.toolBlocks.filterNot { block ->
        hiddenSubAgent(block) || (hideSpeakerTools && block.kind == "tool_use")
    }
}

private class RoundSplit(val rounds: List<ChatRound>, private val roundOfIdx: IntArray) {
    fun roundAt(idx: Int): ChatRound? = rounds.getOrNull(roundOfIdx[idx])
}

/**
 * Pure projection of the message list onto rounds. Runs over whatever list
 * the caller supplies: the frozen prefix build passes a truncated list and
 * therefore folds "the round as far as it goes" (self-consistent — the live
 * streaming message is never part of the frozen prefix), while the live
 * suffix build passes the full merged list and sees complete rounds.
 */
private fun splitRounds(messages: List<ChatMessage>, activeSubAgentToolIds: Set<String>): RoundSplit {
    val roundOfIdx = IntArray(messages.size) { -1 }
    val rounds = mutableListOf<ChatRound>()
    var start = 0
    var lastAssistantIdx = -1
    var running = false
    var thinkingCount = 0
    var toolCount = 0
    var hasFailure = false
    var totalMs = 0L
    val foldableIds = mutableListOf<String>()
    val processTools = mutableListOf<ProcessToolRef>()
    val segments = mutableListOf<ProcessSegment>()
    // The open process run: blocks accumulated since the last reply text.
    var segMessageIdx = -1
    var segFirstId = ""
    var segLastId = ""
    val segIds = mutableSetOf<String>()
    val segSteps = mutableListOf<ProcessStepRef>()
    var segThinking = 0
    var segTools = 0
    var segFailure = false
    var segMs = 0L
    var segRunning = false
    var segActivity = ""
    var segActivityTitle = ""
    var segStartedAt = 0L

    fun flushSegment() {
        if (segSteps.size >= SEGMENT_MIN_STEPS && segMessageIdx >= 0) {
            segments.add(ProcessSegment(
                messageIdx = segMessageIdx,
                firstBlockId = segFirstId,
                lastBlockId = segLastId,
                blockIds = segIds.toSet(),
                thinkingCount = segThinking,
                toolCount = segTools,
                hasFailure = segFailure,
                totalMs = segMs,
                steps = segSteps.toList(),
                running = segRunning,
                activity = segActivity,
                activityTitle = segActivityTitle,
                startedAtMs = segStartedAt,
            ))
        }
        segMessageIdx = -1
        segFirstId = ""
        segLastId = ""
        segIds.clear()
        segSteps.clear()
        segThinking = 0
        segTools = 0
        segFailure = false
        segMs = 0L
        segRunning = false
        segActivity = ""
        segActivityTitle = ""
        segStartedAt = 0L
    }

    fun closeRound(endExclusive: Int) {
        flushSegment()
        if (lastAssistantIdx < 0) return // no assistant payload: nothing to fold
        val round = ChatRound(
            key = messages[lastAssistantIdx].id,
            lastAssistantIdx = lastAssistantIdx,
            isRunning = running,
            foldableSteps = foldableIds.size,
            thinkingCount = thinkingCount,
            toolCount = toolCount,
            hasFailure = hasFailure,
            totalMs = totalMs,
            processTools = processTools.toList(),
            segments = segments.toList(),
        )
        val roundIdx = rounds.size
        rounds.add(round)
        for (i in start until endExclusive) roundOfIdx[i] = roundIdx
    }

    fun resetRound(newStart: Int) {
        start = newStart
        lastAssistantIdx = -1
        running = false
        thinkingCount = 0
        toolCount = 0
        hasFailure = false
        totalMs = 0L
        foldableIds.clear()
        processTools.clear()
        segments.clear()
    }

    messages.forEachIndexed { idx, raw ->
        if (raw.role == "user") {
            closeRound(idx)
            resetRound(idx)
        }
        if (raw.role == "assistant") {
            lastAssistantIdx = idx
            if (raw.isStreaming || raw.isAwaitingModelResponse) running = true
            val blocks = effectiveBlocks(raw, activeSubAgentToolIds)
            processTools += processToolRefs(blocks)
            for (block in blocks) {
                val isProcess = block.kind == "thinking" ||
                    (block.kind == "tool_use" &&
                        !isAlwaysVisibleProcessTool(block) &&
                        !isInFlightProcessTool(block))
                // Reply text (or an always-visible tool) ends the current
                // process run: the card summarises what happened BEFORE the
                // text, which is where the reference puts it.
                if (!isProcess && block.kind == "text" && block.content.isNotEmpty()) {
                    flushSegment()
                }
                if (!isProcess) continue
                if (segMessageIdx < 0) {
                    segMessageIdx = idx
                    segFirstId = block.id
                }
                segLastId = block.id
                segIds += block.id
                segMs += block.durationMs
                if (segStartedAt == 0L && block.startTimeMs > 0L) segStartedAt = block.startTimeMs
                val stepRunning = block.toolStatus in IN_FLIGHT_PROCESS_TOOL_STATUSES ||
                    (block.kind == "thinking" && raw.isStreaming &&
                        block.id == blocks.lastOrNull()?.id)
                if (stepRunning) {
                    segRunning = true
                    // Latest running step wins: the header reports what is
                    // happening NOW, not what happened first.
                    segActivity = if (block.kind == "thinking") "thinking" else "tool"
                    segActivityTitle = if (block.kind == "thinking") ""
                        else block.toolTitle.ifEmpty { block.toolName }
                }
                when (block.kind) {
                    "thinking" -> {
                        thinkingCount++
                        segThinking++
                        foldableIds += block.id
                        totalMs += block.durationMs
                    }
                    "tool_use" -> {
                        toolCount++
                        segTools++
                        totalMs += block.durationMs
                        if (block.toolStatus == ToolBlockStatus.FAILED) {
                            hasFailure = true
                            segFailure = true
                        }
                        foldableIds += block.id
                    }
                }
                segSteps += ProcessStepRef(
                    id = block.id,
                    kind = block.kind,
                    title = if (block.kind == "thinking") ""
                        else block.toolTitle.ifEmpty { block.toolName }.ifEmpty { "tool" },
                    status = block.toolStatus,
                    durationMs = block.durationMs,
                    running = stepRunning,
                )
            }
        }
    }
    closeRound(messages.size)
    return RoundSplit(rounds, roundOfIdx)
}

internal fun buildFlatChatItems(
    messages: List<ChatMessage>,
    // [T-android-perf-logging] Optional — when supplied, emit a progress
    // breadcrumb every 100 messages so a low-memory repro shows which batch
    // drives the heap up. Null (default) skips all progress logging, so the
    // hot per-token streaming rebuild path stays log-free.
    sessionId: String? = null,
    // [T-android-stream-pipeline-incremental] Build rows only for
    // messages[fromIndex, size). Neighbor lookbacks (isResumeContinuation)
    // still read the FULL list, so a suffix built with fromIndex > 0 is
    // row-for-row identical to the same span of a full build — rows never
    // depend on later messages, only earlier ones. (Round fold state is the
    // one deliberate exception on the LIVE side: a running round keeps its
    // earlier messages open too, and the frozen prefix rebuild that fires
    // whenever the canonical list changes re-syncs them.)
    fromIndex: Int = 0,
    // Dedupe continuity for split builds: pass the key set of the frozen
    // prefix so the defensive key-collision suffixing behaves exactly as a
    // single full build would.
    seedKeys: Set<String> = emptySet(),
    showCompletedToolCards: Boolean = true,
    foldAiProcess: Boolean = false,
    // [T-android-round-collapse] Round keys — the id of each round's LAST
    // assistant message (the message that owns the fold bar). The toggle in
    // ChatScreen adds/removes bar.messageId, which IS the round key.
    expandedProcessIds: Set<String> = emptySet(),
    activeSubAgentToolIds: Set<String> = emptySet(),
): List<FlatChatItem> {
    val out = mutableListOf<FlatChatItem>()
    val usedKeys = if (seedKeys.isEmpty()) mutableSetOf() else seedKeys.toMutableSet()
    val roundSplit = if (foldAiProcess) splitRounds(messages, activeSubAgentToolIds) else null
    fun dedupe(item: FlatChatItem): FlatChatItem {
        // Defensive: duplicated keys crash LazyColumn. If any slip through, suffix
        // a counter until unique. This should never fire if upstream dedup is
        // correct. The suffix is appended to the KEY only — never to
        // message.id / messageId (that used to desync every key consumer; see
        // FlatKeys KDoc).
        if (usedKeys.add(item.key)) return item
        var n = 2
        while (!usedKeys.add(item.key + "#$n")) n++
        return item.withKeySuffix("#$n")
    }
    for (idx in fromIndex until messages.size) {
        val rawMessage = messages[idx]
        // Speaker / sub-agent visibility filters live in [effectiveBlocks] so
        // the round pre-pass and this row loop can never disagree about what
        // counts as a foldable step (the bar's totals must match the rows).
        val effBlocks = effectiveBlocks(rawMessage, activeSubAgentToolIds)
        val message = if (effBlocks.size == rawMessage.toolBlocks.size) rawMessage
        else rawMessage.copy(toolBlocks = effBlocks)
        // [T-android-perf-logging] Per-100-message progress breadcrumb.
        // `out.size` is the running row count, so a sudden jump between two
        // progress lines localizes the heavy batch. Only fires on the
        // full-build path (sessionId != null), never per streaming token.
        if (sessionId != null && idx > 0 && idx % 100 == 0) {
            com.openminis.app.diagnostics.PerfLongCtx.step(
                sessionId,
                "buildFlatChatItems.progress",
                "msgIdx=$idx of=${messages.size} rowsSoFar=${out.size}",
            )
        }
        if (message.role == "user") {
            // [T-android-candidate-bubble-gap] Flag when the previous message
            // is also a user message so the bubble can add a separating top
            // gap — back-to-back candidate / queued sends otherwise have no
            // AssistantHeader between them and visually merge.
            out.add(dedupe(FlatChatItem.UserBubble(message)))
            continue
        }
        // System messages (slash-command notices, compact divider, etc.) render
        // as horizontal-divider rows — no "Minis Ultra" attribution, no card. Skip
        // the assistant header so each info block stands on its own. Mirrors
        // iOS systemDividerRow / compactDividerRow.
        val isSystem = message.role == "system"
        val joinedMarkdown = run {
            val parts = message.toolBlocks
                .filter { it.kind == "text" && it.content.isNotEmpty() }
                .joinToString("\n\n") { it.content }
            if (parts.isNotEmpty()) parts else message.content
        }
        // T83: when Resume creates a fresh assistant bubble after the user
        // stopped a streaming turn, the previous (cancelled) assistant
        // message is right before this one in the list. Visually they should
        // read as one continuous turn — suppress the duplicate "Minis Ultra"
        // header. Skip system rows when looking back since they render as
        // dividers, not as separate speaker turns. iOS achieves this by
        // reusing the existing ChatMessage in runAgentLoop(resumingAt:);
        // we reach the same end-result at the render layer.
        val prevNonSystem = (idx - 1 downTo 0).asSequence()
            .map { messages[it] }
            .firstOrNull { it.role != "system" }
        // Resume reuses the previous assistant turn, so a second unnamed bubble
        // must not grow a second soul header. A different group-chat speaker
        // is a new person and always gets their own mark. Same name means the
        // same model continued, not a new participant.
        val prevSpeaker = prevNonSystem?.speakerName?.trim().orEmpty()
        val thisSpeaker = message.speakerName?.trim().orEmpty()
        val isResumeContinuation = prevNonSystem?.role == "assistant" &&
            prevSpeaker == thisSpeaker

        val blocks = message.toolBlocks
        val toolPillBlocks = blocks.filter { it.kind == "tool_use" }
        val lastThinkingId = blocks.lastOrNull { it.kind == "thinking" }?.id
        // [T-android-thinking-auto-collapse] Id of the last block of ANY
        // kind — used to flip the trailing thinking block's auto-collapse
        // signal the moment a subsequent text / tool_use arrives. See
        // AssistantThinking.isLastBlockOverall KDoc.
        val lastBlockId = blocks.lastOrNull()?.id
        val lastTextIdx = blocks.indexOfLast { it.kind == "text" }
        val hasAnyTextBlock = lastTextIdx >= 0
        // Only the last cancelled tool_use in the message gets the Retry button —
        // retryLast() re-runs the whole turn, so one button is enough.
        val lastCancelledToolId = blocks.lastOrNull { it.kind == "tool_use" && it.toolStatus == ToolBlockStatus.CANCELLED }?.id
        // [T-android-round-collapse] One expression replaces the old
        // per-message fold state (hasFoldableProcess + liveThinkingId +
        // processExpanded): a running round is always open (effectiveExpanded
        // = isRunning || expanded), a finished round folds unless the user
        // expanded it, and rounds with ≤ 2 foldable steps never fold at all.
        // roundSplit is null when folding is off, so roundFolded is false.
        val round = roundSplit?.roundAt(idx)
        // [P-process-card] Every process run of ≥ 2 steps is a card, running
        // ones included. Its steps leave the list for good — expanding the
        // card renders them INSIDE the card. A card the user has not opened
        // folds its steps; a card they opened (its own key, not the round's)
        // keeps them in the card either way.
        val foldedBlockIds: Set<String> = if (round == null || isSystem) {
            emptySet()
        } else {
            round.segments.flatMapTo(mutableSetOf()) { it.blockIds }
        }
        val roundFolded = foldedBlockIds.isNotEmpty()
        val keepVisibleIds = emptySet<String>()
        val replyText = AssistantReplyText.joined(blocks)
        // [T-android-fold-toolonly-blank] A turn whose entire visible payload
        // is completed thinking/tool cards collapses into the process summary.
        // Emitting the AssistantHeader row above an otherwise empty turn left
        // header padding + spacedBy(2.dp) rendered as a large blank band in the
        // reverse-layout list. Compute whether anything besides the summary
        // will actually render and skip the header when it will not.
        val headerVisibleInBlocks = blocks.any { block ->
            when (block.kind) {
                "text" -> block.content.isNotEmpty()
                "info" -> true
                "thinking" -> block.id !in foldedBlockIds &&
                    (!roundFolded || block.id in keepVisibleIds)
                "tool_use" -> block.id !in foldedBlockIds && shouldShowProcessToolRow(
                    block,
                    showCompletedToolCards = showCompletedToolCards,
                    foldAiProcess = foldAiProcess,
                    roundFolded = roundFolded,
                    keepVisibleIds = keepVisibleIds,
                )
                else -> false
            }
        }
        val headerHiddenByFold = roundFolded && !headerVisibleInBlocks &&
            message.content.isBlank() && message.error == null
        if (!isSystem && !isResumeContinuation && !headerHiddenByFold) {
            out.add(dedupe(FlatChatItem.AssistantHeader(
                message.id,
                message.speakerName.orEmpty(),
                message.speakerVendor.orEmpty(),
            )))
        }
        blocks.forEachIndexed { index, block ->
            when (block.kind) {
                "text" -> {
                    if (block.content.isNotEmpty()) {
                        val isLastText = index == lastTextIdx
                        // Pattern A: split this text block's content into
                        // independent markdown fragments so each becomes its
                        // own LazyColumn item. Frozen prefix fragments are
                        // anchored separately by LazyList; only the trailing
                        // live fragment can change height during streaming.
                        //
                        // [T-android-defensive-fragment-merge] For a FROZEN
                        // (non-streaming) message, coalesce adjacent
                        // plain-text fragments so a long reply produces a
                        // handful of rows instead of dozens — cuts cold-open
                        // full-build row count ~8x and eases GC pressure on
                        // low-memory devices. The live streaming tail message
                        // keeps fine-grained fragments so only the trailing
                        // paragraph re-parses per token (Pattern A jank
                        // optimization preserved). Code fences stay standalone
                        // either way.
                        val rawFragments = splitMarkdownIntoBlockTexts(block.content)
                        // [T-android-stream-end-reflow-flicker-v18] Preserve
                        // per-fragment FlatChatItem keys across the
                        // streaming→idle boundary. Previously the trailing
                        // text block kept rawFragments only while
                        // `message.isStreaming==true`; the moment it flipped
                        // false the fragments coalesced into fewer rows, all
                        // mdblock:msgId:parentBlockId:N keys for N >= K
                        // suddenly vanished from the flatItems list. That
                        // wipe-and-rebuild was the "整个页面像被重刷" the
                        // user reported — LazyColumn lost every key it was
                        // using to anchor the viewport, fell back to numeric
                        // firstVisibleItemIndex, and parked the viewport on
                        // whatever row happened to take that numeric slot
                        // (often the previous assistant message).
                        //
                        // Fix: keep the live (== last in the list) text block
                        // on rawFragments regardless of isStreaming. The
                        // boundary that actually warrants coalesce is "a
                        // NEWER message exists below this one" — i.e. a
                        // subsequent user turn pushed this assistant turn
                        // into history. Until then, the same key set the
                        // user was scrolled into stays valid.
                        // [T-android-flatitems-sublist-cme] Index-based scan
                        // instead of messages.subList(idx+1, size).all{} — a
                        // subList is a live view sharing the parent's modCount,
                        // which threw ConcurrentModificationException when the
                        // backing list changed under it. A plain index loop
                        // touches no view.
                        val isLastAssistantTurn = idx == messages.lastIndex ||
                            (idx + 1 until messages.size).all { messages[it].role != "assistant" }
                        val fragments = if (isLastText && isLastAssistantTurn) {
                            rawFragments
                        } else {
                            coalesceMarkdownFragments(rawFragments)
                        }
                        if (fragments.isEmpty()) {
                            // Defensive: if the splitter returns nothing for
                            // a non-empty input (shouldn't happen), fall back
                            // to a single fragment so content isn't dropped.
                            out.add(dedupe(FlatChatItem.AssistantMarkdownBlock(
                                messageId = message.id,
                                parentBlockId = block.id,
                                rawText = block.content,
                                blockIndex = 0,
                                isLastBlockOfMessage = isLastText && message.isStreaming,
                                messageIsStreaming = message.isStreaming && isLastText,
                                messageMarkdown = joinedMarkdown,
                                showTranslate = !message.isStreaming && block.content.isNotBlank() &&
                                    (!roundFolded || isLastText),
                                segmentText = if (roundFolded && isLastText) replyText else block.content,
                                translateWholeReply = roundFolded && isLastText &&
                                    !message.isStreaming && block.content.isNotBlank(),
                            )))
                        } else {
                            fragments.forEachIndexed { fragIdx, raw ->
                                val isLastFragOfText = fragIdx == fragments.lastIndex
                                out.add(dedupe(FlatChatItem.AssistantMarkdownBlock(
                                    messageId = message.id,
                                    parentBlockId = block.id,
                                    rawText = raw,
                                    blockIndex = fragIdx,
                                    isLastBlockOfMessage = isLastText && isLastFragOfText,
                                    messageIsStreaming = message.isStreaming && isLastText,
                                    messageMarkdown = joinedMarkdown,
                                    showTranslate = isLastFragOfText && !message.isStreaming && block.content.isNotBlank() &&
                                        (!roundFolded || isLastText),
                                    segmentText = if (roundFolded && isLastText && isLastFragOfText) replyText
                                        else if (isLastFragOfText) block.content else "",
                                    translateWholeReply = roundFolded && isLastText && isLastFragOfText &&
                                        !message.isStreaming && block.content.isNotBlank(),
                                )))
                            }
                        }
                    }
                }
                "thinking" -> {
                    if (block.id !in foldedBlockIds && (!roundFolded || block.id in keepVisibleIds)) {
                        out.add(dedupe(FlatChatItem.AssistantThinking(
                            messageId = message.id,
                            block = block,
                            isLast = block.id == lastThinkingId,
                            messageIsStreaming = message.isStreaming,
                            messageThinkingLevel = message.thinkingLevel,
                            isLastBlockOverall = block.id == lastBlockId,
                        )))
                    }
                }
                "info" -> out.add(dedupe(FlatChatItem.AssistantInfo(
                    messageId = message.id,
                    block = block,
                )))
                else -> if (block.id !in foldedBlockIds && shouldShowProcessToolRow(
                        block,
                        showCompletedToolCards = showCompletedToolCards,
                        foldAiProcess = foldAiProcess,
                        roundFolded = roundFolded,
                        keepVisibleIds = keepVisibleIds,
                    )
                ) {
                    out.add(dedupe(FlatChatItem.AssistantToolUse(
                        messageId = message.id,
                        block = block,
                        allToolBlocks = toolPillBlocks,
                        isLastCancelled = block.id == lastCancelledToolId,
                    )))
                }
            }
            // [P-process-card] The card follows the run's LAST block, so under
            // reverseLayout it sits visually ABOVE the reply that comes next.
            if (round != null && !isSystem) {
                val segment = round.segments.firstOrNull {
                    it.messageIdx == idx && it.lastBlockId == block.id
                }
                if (segment != null) {
                    // The card's own key, so collapsing one card never
                    // touches the next one — manual collapse suppresses
                    // auto-expand for THIS card only.
                    val cardKey = "${round.key}#${segment.firstBlockId}"
                    out.add(dedupe(FlatChatItem.AssistantProcessSummary(
                        messageId = cardKey,
                        thinkingCount = segment.thinkingCount,
                        toolCount = segment.toolCount,
                        expanded = cardKey in expandedProcessIds,
                        hasFailure = segment.hasFailure,
                        processTools = round.processTools,
                        totalMs = segment.totalMs,
                        steps = segment.steps,
                        running = segment.running,
                        activity = segment.activity,
                        activityTitle = segment.activityTitle,
                        startedAtMs = segment.startedAtMs,
                    )))
                }
            }
        }

        // Typing indicator: show while streaming and either (a) no visible
        // content has arrived yet, or (b) we're in the network gap waiting
        // on the model's next response (e.g. after tool results were sent
        // back). Mirrors iOS: `isActiveMessage && (!hasVisibleContent || isAwaitingModelResponse)`.
        //
        // [T-android-typing-hidden-thinking] "Visible" must mean WILL RENDER,
        // not merely "exists". Two blocks used to count as content while
        // drawing nothing, killing the indicator into a blank gap ("thinking
        // 还没等到内容出现就消失了"):
        //  - a "thinking" block when the message's thinking level is OFF —
        //    forced-reasoning models (MiniMax M2, Grok…) still stream
        //    reasoning_content, but ChatScreen suppresses the row when the
        //    snapshot level is disabled (T300), so the user saw nothing;
        //  - a freshly-created "text" block whose content is still empty.
        // A null thinkingLevel snapshot falls back to the chat's CURRENT
        // level in the renderer, which this pure builder can't read — treat
        // it as visible (legacy messages; conservative, old behavior).
        val hasVisibleContent = message.content.isNotEmpty() || blocks.any {
            when (it.kind) {
                "info" -> false
                // [T-android-thinking-forced-visible] A thinking block with
                // content renders (forced-reasoning models stream reasoning
                // even when the request level is OFF), so it counts as
                // visible content for the typing indicator. Empty block =
                // still waiting, same as before.
                "thinking" -> it.content.isNotBlank()
                "text" -> it.content.isNotEmpty()
                else -> true // tool_use pills render immediately
            }
        }
        if (message.isStreaming && (!hasVisibleContent || message.isAwaitingModelResponse)) {
            out.add(dedupe(FlatChatItem.AssistantTyping(message.id)))
        }

        // Legacy fallback: pre-migration sessions stored all text in message.content
        // with no text-kind blocks. Render it after blocks in that case only.
        if (!hasAnyTextBlock && message.content.isNotEmpty()) {
            out.add(dedupe(FlatChatItem.AssistantLegacyContent(
                messageId = message.id,
                content = message.content,
                isStreaming = message.isStreaming,
            )))
        }

        // Inline error banner
        message.error?.let {
            out.add(dedupe(FlatChatItem.AssistantError(message.id, it)))
        }
    }
    return out
}

internal fun shouldShowToolUseRow(block: AssistantBlock, showCompletedToolCards: Boolean): Boolean {
    if (showCompletedToolCards) return true
    return when (block.toolStatus) {
        ToolBlockStatus.SUCCESS, ToolBlockStatus.FAILED, ToolBlockStatus.TIMEOUT -> false
        else -> true
    }
}

private val SUB_AGENT_TRANSCRIPT_TOOLS = setOf("spawn_agent", "run_subagent", "dispatch_agents")

/** Chat cards that duplicate the sub-agent chip. Hidden while chip mode is on. */
internal fun isSubAgentTranscriptCard(block: AssistantBlock): Boolean =
    block.kind == "tool_use" && (
        block.toolName in SUB_AGENT_TRANSCRIPT_TOOLS || "#sub-" in block.id
    )

internal fun isAlwaysVisibleProcessTool(block: AssistantBlock): Boolean =
    block.kind == "tool_use" && block.toolName == "ask_user_question"

internal fun shouldShowProcessToolRow(
    block: AssistantBlock,
    showCompletedToolCards: Boolean,
    foldAiProcess: Boolean,
    roundFolded: Boolean,
    keepVisibleIds: Set<String>,
): Boolean {
    if (isAlwaysVisibleProcessTool(block)) return true
    if (isInFlightProcessTool(block)) return true
    if (roundFolded) return block.id in keepVisibleIds
    // Fold mode owns visibility: a running or user-expanded round shows every
    // step in-thread (the fold bar no longer carries tool chips, so hiding
    // completed tools here would make them unreachable). The
    // showCompletedToolCards setting only governs the fold-OFF mode.
    if (foldAiProcess) return true
    return shouldShowToolUseRow(block, showCompletedToolCards)
}

private val IN_FLIGHT_PROCESS_TOOL_STATUSES = setOf(
    ToolBlockStatus.STREAMING,
    ToolBlockStatus.PENDING,
    ToolBlockStatus.RUNNING,
)

internal fun isInFlightProcessTool(block: AssistantBlock): Boolean =
    block.kind == "tool_use" && block.toolStatus in IN_FLIGHT_PROCESS_TOOL_STATUSES

/** Compact identity for a folded process-summary chip. */
internal data class ProcessToolRef(
    val id: String,
    val title: String,
    val status: ToolBlockStatus?,
)

internal fun processToolRefs(blocks: List<AssistantBlock>): List<ProcessToolRef> =
    blocks.filter { it.kind == "tool_use" }.map { block ->
        ProcessToolRef(
            id = block.id,
            title = block.toolTitle.ifEmpty { block.toolName }.ifEmpty { "tool" },
            status = block.toolStatus,
        )
    }

/** Tool-use rows that belong in the detail sheet (completed or live). */
internal fun isDetailProcessTool(block: AssistantBlock): Boolean {
    if (block.toolStatus == null) return false
    if (block.kind == "thinking" || block.kind == "info") return false
    return true
}

internal fun assistantToolUseBlocks(messages: List<ChatMessage>): List<AssistantBlock> =
    messages.asSequence()
        .filter { it.role == "assistant" }
        .flatMap { it.toolBlocks.asSequence() }
        .filter(::isDetailProcessTool)
        .toList()

/**
 * Whether [block] belongs on the floating tool overlay. When
 * [foldAiProcess] is on, the round model owns process display — a running
 * round renders every step in-list, so a viewport-pinned copy would
 * duplicate rows that are already visible at their own positions. The
 * overlay therefore only serves the fold-OFF mode.
 *
 * The overlay subset is *not* the source of truth for ToolDetailSheet:
 * completed tools must remain openable after they leave the overlay.
 */
internal fun isFloatingProcessTool(
    block: AssistantBlock,
    foldAiProcess: Boolean,
): Boolean {
    if (!isDetailProcessTool(block)) return false
    if (foldAiProcess) return false
    return true
}

/**
 * [P0-4] The blocks the floating activity pill may pin, derived from the
 * LATEST assistant reply. ONE pure projection shared by the pill's mount
 * gate (hasFloatingTools in ChatScreen, synchronous) and its data pipeline
 * (lastToolBlocks, coroutine-side) — previously two hand-maintained filters
 * that could drift: the gate scanned ALL messages while the pipeline read
 * only the latest reply, and neither knew about the showFloatingToolBar
 * pref or the streaming state, which left a 79dp bottom reserve for an
 * overlay that never rendered after a fold-OFF turn ended.
 *
 * Fold-ON returns empty (single channel: the running round renders every
 * step in-list). Sub-agent transcript cards are dropped while the
 * sub-agent bar owns their display.
 */
internal fun floatingOverlayBlocks(
    latestReply: ChatMessage?,
    foldAiProcess: Boolean,
    showSubAgentBar: Boolean,
    activeSubAgentToolIds: Set<String>,
): List<AssistantBlock> = latestReply?.toolBlocks.orEmpty()
    .filter { isFloatingProcessTool(it, foldAiProcess) }
    .filterNot {
        showSubAgentBar && isSubAgentTranscriptCard(it) &&
            (it.id in activeSubAgentToolIds ||
                it.id.substringBefore("#sub-") in activeSubAgentToolIds)
    }

// ── [P1-3] Row rhythm ───────────────────────────────────────────────────
//
// Vertical spacing between list rows, replacing the flat LazyColumn
// spacedBy(2.dp) plus per-row ad-hoc paddings. flatItems is oldest-first and
// rendered via asReversed() under reverseLayout, so the row at index p-1
// renders directly ABOVE the row at index p — the "top gap" of row p is the
// visual gap between p-1 and p, and it is applied as top padding on row p.
//
// Rhythm (taixu ChatMessageList-derived, adapted to our row kinds):
//  - above a user bubble: 12dp turn boundary (16dp between back-to-back
//    user bubbles — candidate/queued pairs, T-android-candidate-bubble-gap);
//  - above an assistant header: 16dp after a user bubble
//    (T-android-user-assistant-spacing-16), else 12dp;
//  - process row → process row: 2.5dp (dense activity cluster);
//  - process row → reply text: 4dp (process hands off to the answer);
//  - header → first row of its turn: 4dp;
//  - md fragment → md fragment of the SAME message: 2dp (paragraph flow);
//  - everything else: 8dp (default breath).

internal val ChatRowDefaultGap: Dp = 8.dp

internal fun isProcessRow(item: FlatChatItem): Boolean =
    item is FlatChatItem.AssistantThinking ||
        item is FlatChatItem.AssistantToolUse ||
        item is FlatChatItem.AssistantProcessSummary

private fun isTextRow(item: FlatChatItem): Boolean =
    item is FlatChatItem.AssistantMarkdownBlock || item is FlatChatItem.AssistantText

internal fun flatItemTopGap(prev: FlatChatItem?, cur: FlatChatItem): Dp = when {
    cur is FlatChatItem.UserBubble ->
        if (prev is FlatChatItem.UserBubble) 16.dp else 12.dp
    cur is FlatChatItem.AssistantHeader ->
        if (prev is FlatChatItem.UserBubble) 16.dp else 12.dp
    prev == null -> 0.dp
    isTextRow(cur) && isTextRow(prev) &&
        (prev as? FlatChatItem.AssistantMarkdownBlock)?.messageId ==
        (cur as? FlatChatItem.AssistantMarkdownBlock)?.messageId -> 2.dp
    isProcessRow(prev) && isProcessRow(cur) -> 2.5.dp
    isProcessRow(prev) && isTextRow(cur) -> 4.dp
    prev is FlatChatItem.AssistantHeader -> 4.dp
    else -> ChatRowDefaultGap
}
